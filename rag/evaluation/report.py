"""Render the experiment matrix into docs/experiments.md.

The file keeps its standing rule: negative results stay in the table. A reranker that
cost 180ms for two points of recall and was not adopted is a more useful row than a
silent omission, and it is the row that shows the decision was made on evidence.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path

from rag.config import get_settings
from rag.evaluation.dataset import EvalSet
from rag.evaluation.metrics import RunMetrics

EXPERIMENTS_PATH = Path("docs/experiments.md")
# The headline benchmark owns docs/experiments.md; other suites get their own file so a
# regression run cannot overwrite the reported numbers.
HEADLINE_SET = "lic-real"


def path_for(set_name: str) -> Path:
    if set_name == HEADLINE_SET:
        return EXPERIMENTS_PATH
    return EXPERIMENTS_PATH.with_name(f"experiments-{set_name}.md")

# Everything between these markers is regenerated; everything outside is hand-written
# and preserved. Without this, each run would wipe the written analysis -- and the
# analysis is the part that makes the numbers mean something.
BEGIN = "<!-- BEGIN GENERATED -->"
END = "<!-- END GENERATED -->"

COLUMNS = [
    ("experiment", "Experiment"),
    ("recall@k", "Recall@k"),
    ("mrr", "MRR"),
    ("ndcg@k", "nDCG@k"),
    ("section", "Section acc."),
    ("false answer", "False answer"),
    ("false abstain", "False abstain"),
    ("cond. coverage", "Cond. coverage"),
    ("p50 ms", "p50 ms"),
    ("tokens/100q", "Tokens/100q"),
]


def render(runs: list[RunMetrics], eval_set: EvalSet, k: int) -> str:
    settings = get_settings()
    first = runs[0] if runs else None

    # A heading, not a title: the document title and the written analysis live outside
    # the generated block so a re-run cannot clobber them.
    lines = [
        "## Current results",
        "",
        f"Generated by `policy experiments` on {date.today().isoformat()}.",
        "",
        f"- Question set: `{eval_set.set_name}` v{eval_set.version} — "
        f"{len(eval_set.questions)} questions "
        f"({len(eval_set.answerable)} answerable, {len(eval_set.unanswerable)} not)",
        f"- k = {k}; candidates per arm = {settings.retrieval_candidates}; "
        f"RRF k = {settings.rrf_k}",
        f"- Embeddings: `{settings.openai_embedding_model}`; "
        f"generation: `{settings.openai_chat_model}`",
        "",
        "Every row runs against the same frozen question set. **Rows that lost stay in "
        "the table** — the negative results are the part that shows the decision was "
        "made on evidence rather than fashion.",
        "",
    ]

    if first is not None and first.false_answer_rate is None:
        lines += [
            "Retrieval-only run: no model was called, so the abstention and token "
            "columns are empty. Run `policy experiments --generate` to fill them.",
            "",
        ]
    elif first is not None and first.repeats > 1:
        lines += [
            f"Generation ran **{first.repeats} times per question** against the same "
            f"retrieved evidence; the abstention columns show the mean rate and half the "
            f"range across those passes. Retrieval ran once, because it is deterministic.",
            "",
        ]
    elif first is not None:
        lines += [
            "Generation ran **once per question**, so the abstention columns carry no "
            "spread. They are not deterministic: one benchmark question was measured "
            "answering 5 times and abstaining 5 out of 10. Use `--repeats` before "
            "comparing these two columns between runs.",
            "",
        ]

    lines.append("| " + " | ".join(label for _, label in COLUMNS) + " |")
    lines.append("|" + "|".join("---" for _ in COLUMNS) + "|")
    for run in runs:
        row = run.as_row()
        lines.append("| " + " | ".join(str(row[key]) for key, _ in COLUMNS) + " |")

    lines += _warnings(runs, k)

    lines += [
        "",
        "## Reading these numbers",
        "",
        "- **Recall@k** and **MRR** are computed over answerable questions only; there "
        "is no evidence to retrieve for the rest.",
        "- Evidence is matched by **page**, not chunk id, so these labels survive "
        "re-chunking. A chunk counts as a hit when its page range covers a labelled page.",
        "- **Section acc.** is the stricter check: the right page for the right reason. "
        "A page can hold several clauses.",
        "- Postgres full-text ranking is `ts_rank_cd`, **not BM25**. The `bm25` row is "
        "real BM25 (`rank_bm25`, in memory) so the comparison is measured rather than "
        "asserted.",
        "- **Cond. coverage** applies to questions whose honest answer is conditional. "
        "They are excluded from the two rates above -- neither answering nor abstaining "
        "is wrong when the document holds several competing conditions -- and scored "
        "instead on whether *every* condition reached the model.",
        "- Per-question output for every row is in `evals/results/`.",
        "",
    ]
    return "\n".join(lines)


def _warnings(runs: list[RunMetrics], k: int) -> list[str]:
    """Make the table state its own limits.

    A reader who sees Recall@5 = 1.000 across every row should not be left to work out
    for themselves that the benchmark is saturated and the comparison is meaningless.
    The table says so.
    """
    out: list[str] = []
    if not runs:
        return out

    recalls = {run.recall_at_k for run in runs}
    sections = {run.section_accuracy for run in runs}

    if len(recalls) == 1 and recalls == {1.0}:
        out += [
            "",
            f"> **This table does not discriminate at k={k}.** Every configuration scores "
            f"Recall@{k} = 1.000, which means the cut-off is wide relative to the corpus, "
            f"not that retrieval is solved. Re-run at a smaller k, and treat these rows as "
            f"evidence about the benchmark rather than about the strategies.",
        ]
    if len(sections) == 1 and sections == {1.0}:
        out += [
            "",
            "> Section accuracy is 1.000 everywhere for the same reason — too few chunks "
            "per page for the stricter check to separate anything.",
        ]

    spread = max(run.mrr for run in runs) - min(run.mrr for run in runs)
    if spread < 0.02 and len(runs) > 1:
        out += [
            "",
            f"> MRR spread across all configurations is {spread:.3f}. That is inside the "
            f"noise floor of a set this small; no ranking conclusion should be drawn from it.",
        ]
    return out


def write(runs: list[RunMetrics], eval_set: EvalSet, k: int) -> Path:
    """Replace the generated block, preserving hand-written analysis around it."""
    target = path_for(eval_set.set_name)
    target.parent.mkdir(parents=True, exist_ok=True)
    generated = f"{BEGIN}\n\n{render(runs, eval_set, k)}\n{END}"

    if target.exists():
        existing = target.read_text()
        if BEGIN in existing and END in existing:
            head = existing[: existing.index(BEGIN)]
            tail = existing[existing.index(END) + len(END) :]
            target.write_text(head + generated + tail)
            return target

    target.write_text(generated + "\n")
    return target
